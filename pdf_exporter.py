import io
from datetime import datetime
from typing import Dict, Any, List
import pandas as pd

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable, KeepTogether
from reportlab.pdfgen import canvas

class NumberedCanvas(canvas.Canvas):
    """Adds page numbers and header/footer to each page."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, letter[1] - 36, "DataMind AI — Maceco Analytics Executive Report")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, letter[1] - 42, letter[0] - 54, letter[1] - 42)

        # Footer
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 54, 36, footer_text)
        self.drawString(54, 36, "CONFIDENTIAL & PROPRIETARY — Generated by DataMind AI")
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 48, letter[0] - 54, 48)
        self.restoreState()

def generate_pdf_report(
    filename: str,
    overview: Dict[str, Any],
    kpis: List[Dict[str, Any]],
    performers: List[Dict[str, Any]],
    anomalies: List[Dict[str, Any]],
    recommendations: List[Dict[str, Any]],
    quality: Dict[str, Any]
) -> io.BytesIO:
    """Generates an executive business analytics PDF report."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    styles = getSampleStyleSheet()
    
    # Custom color palette matching the SaaS platform
    primary_color = colors.HexColor("#4F46E5")
    dark_neutral = colors.HexColor("#172033")
    slate_color = colors.HexColor("#64748B")
    border_color = colors.HexColor("#E2E8F0")
    bg_light = colors.HexColor("#F8FAFC")

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=24,
        leading=28,
        textColor=primary_color,
        spaceAfter=4
    )
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=11,
        leading=15,
        textColor=slate_color,
        spaceAfter=14
    )
    h2_style = ParagraphStyle(
        'Heading2',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=15,
        leading=18,
        textColor=dark_neutral,
        spaceBefore=14,
        spaceAfter=8
    )
    body_style = ParagraphStyle(
        'Body',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=dark_neutral
    )
    table_header_style = ParagraphStyle(
        'TableHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#334155")
    )
    table_cell_style = ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=dark_neutral
    )

    story = []

    # 1. Header Banner
    story.append(Paragraph("DataMind AI — Maceco Analytics", title_style))
    story.append(Paragraph(f"Executive Business Performance & Quality Report • Dataset: <b>{filename}</b>", subtitle_style))
    story.append(Paragraph(f"Generated on {datetime.now().strftime('%B %d, %Y at %I:%M %p')}", ParagraphStyle('Meta', parent=subtitle_style, fontSize=9, spaceAfter=8)))
    story.append(HRFlowable(width="100%", thickness=1.5, color=primary_color, spaceAfter=14))

    # 2. Dataset Overview & Data Quality Card
    story.append(Paragraph("1. Executive Overview & Data Health", h2_style))
    
    overview_table_data = [
        [
            Paragraph("<b>Total Records:</b>", table_cell_style),
            Paragraph(f"{overview.get('row_count', 0):,}", table_cell_style),
            Paragraph("<b>Total Features:</b>", table_cell_style),
            Paragraph(f"{overview.get('column_count', 0)} attributes", table_cell_style),
        ],
        [
            Paragraph("<b>Data Quality Score:</b>", table_cell_style),
            Paragraph(f"<b>{quality.get('score', 100):.1f}% ({quality.get('grade', 'Good')})</b>", table_cell_style),
            Paragraph("<b>Duplicate Records:</b>", table_cell_style),
            Paragraph(f"{quality.get('duplicate_rows', 0)} ({quality.get('duplicate_pct', 0.0)}%)", table_cell_style),
        ],
        [
            Paragraph("<b>Missing Cells:</b>", table_cell_style),
            Paragraph(f"{quality.get('total_missing', 0):,} ({quality.get('missing_pct', 0.0)}%)", table_cell_style),
            Paragraph("<b>Timeline Span:</b>", table_cell_style),
            Paragraph(f"{overview.get('date_range') or 'Not Detected'}", table_cell_style),
        ]
    ]
    t_overview = Table(overview_table_data, colWidths=[120, 130, 120, 134])
    t_overview.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), bg_light),
        ('BOX', (0, 0), (-1, -1), 0.5, border_color),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]))
    story.append(t_overview)
    story.append(Spacer(1, 14))

    # 3. Key Performance Indicators (KPIs)
    if kpis:
        story.append(Paragraph("2. Key Performance Indicators", h2_style))
        kpi_table_data = [[
            Paragraph("Metric", table_header_style),
            Paragraph("Calculated Value", table_header_style),
            Paragraph("Context / Attribute", table_header_style)
        ]]
        for item in kpis[:8]:
            kpi_table_data.append([
                Paragraph(f"<b>{item.get('label', '')}</b>", table_cell_style),
                Paragraph(f"<font color='#4F46E5'><b>{item.get('value', '')}</b></font>", table_cell_style),
                Paragraph(item.get('detail') or 'Aggregate', table_cell_style),
            ])
        t_kpis = Table(kpi_table_data, colWidths=[170, 150, 184])
        t_kpis.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#EEF2FF")),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(t_kpis)
        story.append(Spacer(1, 14))

    # 4. Critical Performers & Extremes
    if performers:
        story.append(Paragraph("3. Critical Performers & Extremes", h2_style))
        perf_table_data = [[
            Paragraph("Category / Attribute", table_header_style),
            Paragraph("Leading Entity", table_header_style),
            Paragraph("Metric", table_header_style),
            Paragraph("Performance Value", table_header_style),
        ]]
        for p in performers[:6]:
            perf_table_data.append([
                Paragraph(p.get('title', ''), table_cell_style),
                Paragraph(f"<b>{p.get('entity', '')}</b>", table_cell_style),
                Paragraph(p.get('metric', ''), table_cell_style),
                Paragraph(f"<font color='#4F46E5'><b>{p.get('value', '')}</b></font>", table_cell_style),
            ])
        t_perf = Table(perf_table_data, colWidths=[130, 140, 100, 134])
        t_perf.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), bg_light),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(t_perf)
        story.append(Spacer(1, 14))

    # 5. Detected Statistical Anomalies
    if anomalies:
        story.append(KeepTogether([
            Paragraph("4. Automated Anomaly Detection", h2_style),
            Paragraph("Statistical outliers identified using Scikit-Learn Isolation Forest & IQR analysis:", subtitle_style)
        ]))
        anom_table_data = [[
            Paragraph("Severity", table_header_style),
            Paragraph("Metric", table_header_style),
            Paragraph("Observed Value", table_header_style),
            Paragraph("Expected Range", table_header_style),
            Paragraph("Statistical Explanation", table_header_style),
        ]]
        for a in anomalies[:5]:
            sev = a.get('severity', 'Medium')
            sev_color = "#DC2626" if sev == "High" else "#D97706" if sev == "Medium" else "#2563EB"
            anom_table_data.append([
                Paragraph(f"<font color='{sev_color}'><b>{sev}</b></font>", table_cell_style),
                Paragraph(f"<b>{a.get('metric', '')}</b>", table_cell_style),
                Paragraph(str(a.get('observed_value', '')), table_cell_style),
                Paragraph(str(a.get('expected_range', '')), table_cell_style),
                Paragraph(a.get('explanation', ''), table_cell_style),
            ])
        t_anom = Table(anom_table_data, colWidths=[55, 95, 95, 95, 164])
        t_anom.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), bg_light),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(t_anom)
        story.append(Spacer(1, 14))

    # 6. Strategic Business Recommendations
    if recommendations:
        story.append(KeepTogether([
            Paragraph("5. Strategic Recommendations & Next Steps", h2_style),
            Paragraph("Evidence-backed operational strategies generated from verified metrics:", subtitle_style)
        ]))
        rec_table_data = [[
            Paragraph("#", table_header_style),
            Paragraph("Category", table_header_style),
            Paragraph("Analytical Finding", table_header_style),
            Paragraph("Actionable Strategy", table_header_style),
        ]]
        for idx, r in enumerate(recommendations[:6], 1):
            rec_table_data.append([
                Paragraph(f"#{idx}", table_cell_style),
                Paragraph(f"<b>{r.get('category', 'Recommendation').title()}</b>", table_cell_style),
                Paragraph(r.get('finding', ''), table_cell_style),
                Paragraph(f"<b>{r.get('recommendation', '')}</b>", table_cell_style),
            ])
        t_rec = Table(rec_table_data, colWidths=[24, 85, 185, 210])
        t_rec.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#ECFDF5")),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(t_rec)

    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer
